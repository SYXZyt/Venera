#!/usr/bin/env python3
"""Generates src/venera/ErrorCode.cpp from the ErrorCode enum in src/venera/ErrorCode.h.

Each enumerator (e.g. E0001_GENERIC_ERROR) maps to its code prefix (e.g. "E0001").
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "src" / "venera" / "ErrorCode.h"
SOURCE = ROOT / "src" / "venera" / "ErrorCode.cpp"

ENUM_RE = re.compile(r"enum\s+class\s+ErrorCode\b[^{]*\{(.*?)\}", re.DOTALL)
ENTRY_RE = re.compile(r"\b([EWT]\d{4})_\w+")


def parse_codes(header: str) -> list[tuple[str, str]]:
    match = ENUM_RE.search(header)
    if not match:
        sys.exit(f"error: could not find 'enum class ErrorCode' in {HEADER}")

    # Strip comments so commented-out entries are ignored
    body = re.sub(r"//.*?$|/\*.*?\*/", "", match.group(1), flags=re.DOTALL | re.MULTILINE)

    entries = [(m.group(0), m.group(1)) for m in ENTRY_RE.finditer(body)]

    seen = {}
    for name, code in entries:
        if code in seen:
            sys.exit(f"error: duplicate code {code} ({seen[code]} and {name})")
        seen[code] = name

    return entries


def generate(entries: list[tuple[str, str]]) -> str:
    lines = [
        "// AUTO-GENERATED by scripts/generate_error_codes.py - do not edit by hand",
        '#include "ErrorCode.h"',
        "",
        "const char* Venera::ToString(ErrorCode code)",
        "{",
        "    switch (code)",
        "    {",
    ]
    for name, code in entries:
        lines.append(f'        case ErrorCode::{name}: return "{code}";')
    lines += [
        '        default: return "UNKNOWN";',
        "    }",
        "}",

    ]
    return "\n".join(lines)


def main() -> None:
    entries = parse_codes(HEADER.read_text())
    output = generate(entries)

    if SOURCE.exists() and SOURCE.read_text() == output:
        print(f"{SOURCE.relative_to(ROOT)} is up to date")
        return

    SOURCE.write_text(output)
    print(f"Wrote {len(entries)} error codes to {SOURCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
